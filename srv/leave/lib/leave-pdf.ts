import { rgb, type PDFFont, type PDFPage } from "pdf-lib";
import { colors, createPdf, formatDate } from "../../lib/pdf.js";

/** Renders the annual leave request form as a PDF. */

export type LeaveFormData = {
  number: string;
  requestedOn: string;
  employee: { id: string; name: string; department?: string | null; manager?: string | null };
  startDate: string;
  endDate: string;
  returnDate: string;
  workingDays: number;
  skippedDays: { date: string; reason: string }[];
  /** The whole break, weekends and holidays around the leave included. */
  timeOff?: { from: string; to: string; calendarDays: number };
  reason?: string | null;
  balance: { year: number; entitlement: number; usedBefore: number; remainingAfter: number };
  status: string;
  /** The manager's decision, once there is one. */
  decision?: { by: string; on: string; note?: string | null };
};

const STATUS: Record<string, string> = {
  submitted: "Waiting for approval",
  approved: "Approved",
  rejected: "Rejected",
  cancelled: "Cancelled",
};

const days = (n: number) => (n === 1 ? "day" : "days");
const skippedLabel = (reason: string) => (reason === "weekend" ? "Weekend" : reason);

export async function buildLeavePdf(data: LeaveFormData): Promise<Uint8Array> {
  const { doc, regular, bold } = await createPdf(`Annual Leave Request ${data.number}`, data.employee.name);

  const page = doc.addPage([595.28, 841.89]); // A4
  const left = 56;
  const width = page.getWidth() - 2 * left;
  let y = page.getHeight() - 64;
  const { ink, quiet, rule } = colors;

  const text = (s: string, x: number, size = 10.5, font: PDFFont = regular, color = ink) =>
    page.drawText(s, { x, y, size, font, color });
  const line = () => {
    page.drawLine({ start: { x: left, y }, end: { x: left + width, y }, thickness: 0.75, color: rule });
  };
  const section = (title: string) => {
    y -= 26;
    text(title, left, 12, bold);
    y -= 8;
    line();
    y -= 18;
  };
  const row = (label: string, value: string) => {
    text(label, left, 10.5, regular, quiet);
    text(value, left + 170, 10.5, regular);
    y -= 18;
  };

  text("ANNUAL LEAVE REQUEST FORM", left, 18, bold);
  y -= 22;
  text(`Request no.: ${data.number}    Requested on: ${formatDate(data.requestedOn)}`, left, 10, regular, quiet);

  section("Employee");
  row("Name", data.employee.name);
  row("Personnel no.", data.employee.id);
  if (data.employee.department) row("Department", data.employee.department);
  if (data.employee.manager) row("Manager", data.employee.manager);

  section("Leave");
  row("Type", "Annual leave");
  row("First day", formatDate(data.startDate));
  row("Last day", formatDate(data.endDate));
  row("Back at work", formatDate(data.returnDate));
  row("Duration", `${data.workingDays} working ${days(data.workingDays)}`);
  for (const s of data.skippedDays) row("Not counted", `${formatDate(s.date)} (${skippedLabel(s.reason)})`);
  if (data.timeOff && data.timeOff.calendarDays > data.workingDays) {
    row("Time off", `${formatDate(data.timeOff.from)} – ${formatDate(data.timeOff.to)} (${data.timeOff.calendarDays} days)`);
  }
  if (data.reason) row("Reason", data.reason);
  row("Status", STATUS[data.status] ?? data.status);

  section(`Leave balance ${data.balance.year}`);
  row("Annual entitlement", `${data.balance.entitlement} ${days(data.balance.entitlement)}`);
  row("Used before this request", `${data.balance.usedBefore} ${days(data.balance.usedBefore)}`);
  row("This request", `${data.workingDays} ${days(data.workingDays)}`);
  row("Remaining after", `${data.balance.remainingAfter} ${days(data.balance.remainingAfter)}`);

  if (data.decision) {
    // The decision itself is the Status row above.
    section("Manager decision");
    row("Decided by", data.decision.by);
    row("Decided on", formatDate(data.decision.on));
    if (data.decision.note) row("Note", data.decision.note);
  }

  y -= data.decision ? 28 : 40;
  signatures(page, regular, bold, left, width, y, ink, quiet, rule);

  page.drawText("This form was generated by the HR assistant at the employee's request.", {
    x: left,
    y: 40,
    size: 8.5,
    font: regular,
    color: quiet,
  });

  return doc.save();
}

function signatures(
  page: PDFPage,
  regular: PDFFont,
  bold: PDFFont,
  left: number,
  width: number,
  y: number,
  ink: ReturnType<typeof rgb>,
  quiet: ReturnType<typeof rgb>,
  rule: ReturnType<typeof rgb>,
) {
  const boxes = ["Employee", "Manager", "Human Resources"];
  const gap = 16;
  const boxWidth = (width - gap * 2) / 3;
  boxes.forEach((title, i) => {
    const x = left + i * (boxWidth + gap);
    page.drawText(title, { x, y, size: 10.5, font: bold, color: ink });
    page.drawLine({ start: { x, y: y - 48 }, end: { x: x + boxWidth, y: y - 48 }, thickness: 0.75, color: rule });
    page.drawText("Signature / Date", { x, y: y - 62, size: 9, font: regular, color: quiet });
  });
}
